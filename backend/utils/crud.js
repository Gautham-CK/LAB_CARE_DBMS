// Reusable CRUD router. One function builds all 5 standard endpoints for a table:
//   GET    /          -> list (supports ?column=value filters, ?order=col&asc=false, ?limit=10)
//   GET    /:id       -> read one
//   POST   /          -> create
//   PUT    /:id       -> update (PATCH works too)
//   DELETE /:id       -> delete
const express = require('express');
const supabase = require('../supabaseClient');

const RESERVED = ['order', 'asc', 'limit'];

// Turns PostgreSQL error codes into clear messages + correct HTTP status.
function sendError(res, error) {
  const code = error.code;
  let status = 400;
  let hint = null;

  if (code === '23505') { status = 409; hint = 'Duplicate value: a UNIQUE column already has this value.'; }
  else if (code === '23503') { status = 409; hint = 'Foreign key problem: the referenced record does not exist, or other records still depend on this one.'; }
  else if (code === '23514') { status = 400; hint = 'CHECK constraint failed: value is not in the allowed list/range.'; }
  else if (code === '23502') { status = 400; hint = 'A required (NOT NULL) value is missing.'; }
  else if (code === '22P02') { status = 400; hint = 'A value has the wrong format (e.g. text where a number is expected).'; }
  else if (code === 'P0001') { status = 400; hint = 'Blocked by a database trigger/function rule.'; }

  return res.status(status).json({ error: error.message, hint, code });
}

function makeCrudRouter({ table, pk, label, alias, required = [] }) {
  const router = express.Router();

  // LIST
  router.get('/', async (req, res) => {
    try {
      let q = supabase.from(table).select('*');
      for (const [key, value] of Object.entries(req.query)) {
        if (RESERVED.includes(key)) continue;
        q = q.eq(key, value);
      }
      q = q.order(req.query.order || pk, { ascending: req.query.asc !== 'false' });
      if (req.query.limit) q = q.limit(Number(req.query.limit));

      const { data, error } = await q;
      if (error) return sendError(res, error);
      res.json({ count: data.length, data });
    } catch (err) {
      res.status(500).json({ error: err.message });
    }
  });

  // READ ONE
  router.get('/:id', async (req, res) => {
    try {
      const { data, error } = await supabase.from(table).select('*').eq(pk, req.params.id).maybeSingle();
      if (error) return sendError(res, error);
      if (!data) return res.status(404).json({ error: `${label} not found` });
      res.json({ data });
    } catch (err) {
      res.status(500).json({ error: err.message });
    }
  });

  // CREATE
  router.post('/', async (req, res) => {
    try {
      const body = { ...req.body };
      delete body[pk]; // id is generated by the database

      const missing = required.filter((f) => body[f] === undefined || body[f] === null || body[f] === '');
      if (missing.length) {
        return res.status(400).json({ error: `Missing required field(s): ${missing.join(', ')}` });
      }

      const { data, error } = await supabase.from(table).insert([body]).select().single();
      if (error) return sendError(res, error);

      const payload = { message: `${label} created successfully!`, data };
      if (alias) payload[alias] = data;
      res.status(201).json(payload);
    } catch (err) {
      res.status(500).json({ error: err.message });
    }
  });

  // UPDATE
  const update = async (req, res) => {
    try {
      const body = { ...req.body };
      delete body[pk];
      if (Object.keys(body).length === 0) {
        return res.status(400).json({ error: 'Nothing to update: send at least one field' });
      }

      const { data, error } = await supabase.from(table).update(body).eq(pk, req.params.id).select().maybeSingle();
      if (error) return sendError(res, error);
      if (!data) return res.status(404).json({ error: `${label} not found` });
      res.json({ message: `${label} updated successfully!`, data });
    } catch (err) {
      res.status(500).json({ error: err.message });
    }
  };
  router.put('/:id', update);
  router.patch('/:id', update);

  // DELETE
  router.delete('/:id', async (req, res) => {
    try {
      const { data, error } = await supabase.from(table).delete().eq(pk, req.params.id).select();
      if (error) return sendError(res, error);
      if (!data || data.length === 0) return res.status(404).json({ error: `${label} not found` });
      res.json({ message: `${label} deleted successfully!`, data: data[0] });
    } catch (err) {
      res.status(500).json({ error: err.message });
    }
  });

  return router;
}

module.exports = { makeCrudRouter, sendError };
